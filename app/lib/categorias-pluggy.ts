/** "Groceries" → "Mercado"; o que não for conhecido volta como veio. */
export function categoriaPluggyEmPortugues(categoria: string | null | undefined): string | null {
  const nome = (categoria ?? '').trim()
  if (!nome) return null
  return TRADUCOES[nome.toLowerCase()] ?? nome
}
